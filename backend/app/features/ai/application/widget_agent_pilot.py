"""Conservative feature-flagged widget agent pilot.

Only standalone greetings can enter this pilot. Existing deterministic
commerce, follow-up, catalog and knowledge paths retain precedence.
"""

import re
from uuid import UUID

from app.core.config import settings
from app.features.ai.application.conversation_agent_runtime import run_read_only_agent_turn
from app.features.ai.application.conversation_context_builder import build_agent_input
from app.features.ai.application.intent_routing.deterministic import assess_deterministic_route
from app.features.ai.application.intent_routing.schemas import Intent
from app.features.ai.application.conversation_understanding import understand_conversation_turn
from app.features.ai.application.widget_replies import finish_widget_reply, widget_reply_is_stale


def eligible_for_widget_agent_pilot(
    message: str, transcript: list[dict[str, str]]
) -> bool:
    if not settings.ai_conversation_llm_first_enabled:
        return False
    # Pilot only on first-contact greetings; previous turns may contain private\n    # or store-specific context not yet covered by semantic grounding.\n    if any(turn.get("sender") in {"customer", "user", "assistant"}\n           and turn.get("content", "").strip() != message.strip()\n           for turn in transcript):\n        return False\n    understanding = understand_conversation_turn(message, transcript)
    if (
        understanding.negated_action
        or understanding.needs_clarification
        or understanding.contextual_follow_up
        or understanding.multi_intent
    ):
        return False
    assessment = assess_deterministic_route(message, transcript)
    return (
        assessment.intent == Intent.GREETING
        and not assessment.requires_tools
        and not assessment.requires_knowledge
        and assessment.risk_level == "low"
    )


async def try_complete_widget_agent_pilot(
    *,
    organization_id: UUID,
    execution_id: UUID,
    ai_agent_id: UUID,
    message: str,
    transcript: list[dict[str, str]],
    delivery_mode: str,
) -> bool:
    if not eligible_for_widget_agent_pilot(message, transcript):
        return False
    # Existing execution ownership and latest-message checks remain authoritative.
    if await widget_reply_is_stale(organization_id, execution_id):
        return True
    try:
        result = await run_read_only_agent_turn(
            organization_id=organization_id,
            ai_agent_id=ai_agent_id,
            agent_input=build_agent_input(message, transcript, channel="widget"),
        )
    except (ValueError, PermissionError, LookupError):
        # Model-plan validation failures fall back to the existing widget path.
        return False
    if (result.tool_names or not result.answer.strip()
        or len(result.answer) > 500 or re.search(r"\\d", result.answer)):
        # Greeting pilot must not publish quantitative store claims.
        return False
    await finish_widget_reply(
        organization_id,
        execution_id,
        draft=result.answer,
        reply_status="draft_ready" if delivery_mode == "draft_only" else "sent",
        safe_summary="Greeting generated by the opt-in read-only conversation agent.",
        citations=[],
        outcomes=[{"tool": "conversation_agent", "status": "completed", "mode": "greeting_pilot"}],
        usage=result.usage,
        model_name=result.model_name,
    )
    return True
